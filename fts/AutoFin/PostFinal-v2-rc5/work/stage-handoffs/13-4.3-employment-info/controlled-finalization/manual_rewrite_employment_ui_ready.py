def render_list(items: list[str]) -> str:
    if len(items) == 1 and items[0] == "Не требуются.":
        return "Не требуются."
    return "\n".join(f"- {item}" for item in items)


def render_steps(items: list[str]) -> str:
    return "\n".join(f"{index}. {item}" for index, item in enumerate(items, start=1))


def build() -> str:
    existing = TC_PATH.read_text(encoding="utf-8")
    metadata = parse_existing_metadata(existing)
    missing = sorted(set(metadata) ^ set(CASES))
    if missing:
        raise SystemExit(f"Case set mismatch: {missing}")

    output: list[str] = ["# Тест-кейсы: 4-3-employment-info", ""]
    for index in range(1, 84):
        tc_id = f"TC-EMP-{index:03d}"
        meta = metadata[tc_id]
        case = CASES[tc_id]
        title = str(case["title"])
        case_type = str(case.get("type", meta["Тип"]))
        priority = str(case.get("priority", meta["Приоритет"]))
        package_id = str(meta["package_id"])
        trace = str(meta["Трассировка"])
        question = case.get("question")
        is_candidate = question is not None

        output.extend(
            [
                f"## {tc_id}",
                "",
                f"**№:** {index}",
                f"**Название:** {title}",
                f"**Тип:** {case_type}",
                f"**Приоритет:** {priority}",
                f"**package_id:** {package_id}",
                f"**Трассировка:** {trace}",
            ]
        )
        if is_candidate:
            output.extend(
                [
                    "**Статус oracle:** ui-calibration-required",
                    "**Статус тест-кейса:** candidate-ui-calibration",
                    "**Статус автоматизации:** blocked-observability",
                    f"**Требуется подтверждение:** {question}",
                ]
            )
        else:
            output.extend(
                [
                    "**Статус тест-кейса:** confirmed",
                    "**Статус автоматизации:** confirmed",
                ]
            )

        output.extend(
            [
                "",
                "### Предусловия",
                "",
                render_steps(list(case.get("pre", BASE_PRECONDITIONS))),
                "",
                "### Тестовые данные",
                "",
                render_list(list(case.get("data", ["Не требуются."]))),
                "",
                "### Шаги",
                "",
                render_steps(list(case["steps"])),
                "",
                "### Итоговый ожидаемый результат",
                "",
                str(case["expected"]),
                "",
                "### Постусловия",
                "",
                str(case.get("post", "Не требуются.")),
                "",
            ]
        )

    return "\n".join(output).rstrip() + "\n"


if __name__ == "__main__":
    TC_PATH.write_text(build(), encoding="utf-8", newline="\n")
