def parse_existing_metadata(text: str) -> dict[str, dict[str, str]]:
    blocks = re.split(r"(?=^## TC-)", text, flags=re.M)
    metadata: dict[str, dict[str, str]] = {}
    for block in blocks:
        if not block.startswith("## TC-"):
            continue
        lines = block.splitlines()
        tc_id = lines[0].replace("## ", "").strip()
        fields: dict[str, str] = {}
        for line in lines:
            if line.startswith("**") and ":**" in line:
                label = line[2 : line.index(":**")]
                value = line[line.index(":**") + 3 :].strip()
                fields[label] = value
        metadata[tc_id] = fields
    return metadata


